#!/usr/bin/env python3
"""Build a PLCopenXML import file from src/.

src/ files are in paste format (// ===== Declaration ===== / // ===== Implementation =====
markers, no END_ keywords). This script turns them into full ST source in build/st/ and runs
the codesys-st skill's converter to produce build/MotionLad_Import.xml.

Objects with methods, properties or interfaces are not supported by the converter. They are
split into paste-ready pieces in build/manual/<Object>/, and build/manual/README.md lists
every manual step (libraries, objects to create, and what to check after import, taken from
the converter's warnings).

Usage:  python3 tools/build_import.py
"""
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT = ROOT / "build"
CONVERTER = Path.home() / ".claude/skills/codesys-st/scripts/st_to_plcopenxml.py"

DECL = "// ===== Declaration ====="
IMPL = "// ===== Implementation ====="
OOP_RE = re.compile(r"^\s*(INTERFACE|METHOD|PROPERTY)\b", re.M)
HEADER_RE = re.compile(r"^\s*(PROGRAM|FUNCTION_BLOCK|FUNCTION)\s+\w+", re.M)
SECTION_RE = re.compile(r"^// ===== (.+?) =====\s*$", re.M)

# Manual steps that don't come from the sources. Keep in step with src/README.md.
LIBRARIES = [
    ("Standard", "TON (usually already in the project)"),
    ("CXA_DriveUtil", "MB_PowerSupplyDriveIntegrated"),
    ("CXA_Motion", "ML_ motion functions"),
    ("CXA_Datalayer", "DL_MemUser, DL_NODEVALUE, DL_RESULT (RT axis status)"),
    ("CXA_AutomationCore_fbs", "comm_datalayer_MemoryMap, comm_datalayer_Variable (RT map parsing)"),
]
# How to create each manual object in the device tree, by its kind
CREATE_HOWTO = {
    "INTERFACE": "Add Object → Interface `{name}`. Then, for each method file, right-click the "
                 "interface → Add Object → Method (name from the file) and paste the declaration.",
    "FUNCTION_BLOCK": "Add Object → POU → Function Block `{name}`{implements}. Paste the "
                      "declaration and implementation. If the IDE generated method stubs from the "
                      "interface, paste into them; otherwise right-click the FB → Add Object → "
                      "Method / Property. For a property, delete the Set accessor unless a Set file "
                      "is given.",
}


def to_full_st(text: str) -> str:
    if DECL not in text:
        return text                                  # DUT or GVL: already complete
    decl = text.split(DECL, 1)[1].split(IMPL, 1)[0]
    impl = text.split(IMPL, 1)[1] if IMPL in text else ""
    kind = HEADER_RE.search(decl).group(1)
    return f"{decl.strip()}\n{impl.strip()}\nEND_{kind}\n"


def split_sections(text):
    """[(title, body)] for each '// ===== title =====' section; the header comment comes first."""
    parts = SECTION_RE.split(text)
    header = parts[0].strip()
    return header, [(parts[i].strip(), parts[i + 1].strip()) for i in range(1, len(parts), 2)]


def slug(title):
    return re.sub(r"[^A-Za-z0-9]+", "_", title).strip("_")


def write_manual(path, man_dir):
    """Split one OOP source into numbered paste files. Returns (name, kind, implements, header, files)."""
    text = path.read_text(encoding="utf-8")
    header, sections = split_sections(text)
    m = re.search(r"^\s*(INTERFACE|FUNCTION_BLOCK)\s+(\w+)(?:\s+IMPLEMENTS\s+(\w+))?", text, re.M)
    kind, name, implements = m.group(1), m.group(2), m.group(3)
    obj_dir = man_dir / name
    obj_dir.mkdir(parents=True)
    files = []
    for i, (title, body) in enumerate(sections, 1):
        out = obj_dir / f"{i:02d}_{slug(title)}.st"
        out.write_text(f"// {name}: {title}\n{body}\n", encoding="utf-8")
        files.append((out.relative_to(man_dir), title))
    return name, kind, implements, header, files


def write_manual_readme(man_dir, objects, warnings):
    lines = [
        "# Manual steps for the PLCopenXML import",
        "",
        "GENERATED by `tools/build_import.py`. Don't edit it here; it is rebuilt on every build.",
        "",
        "Do the steps in this order. Objects in step 2 must exist before the import, because the "
        "imported code uses them.",
        "",
        "## 1. Libraries (Library Manager → Add library)",
        "",
    ]
    lines += [f"- [ ] **{lib}**: {use}" for lib, use in LIBRARIES]
    lines += ["", "## 2. Create these objects by hand (the converter can't do interfaces, methods or properties)", ""]
    for name, kind, implements, header, files in objects:
        impl_txt = f" with *Implements* `{implements}`" if implements else ""
        lines += [f"### `{name}` ({kind.lower().replace('_', ' ')})", ""]
        notes = [ln.lstrip("/ ").rstrip() for ln in header.splitlines() if ln.strip()]
        if notes:
            lines += ["> " + " ".join(notes), ""]
        lines += [CREATE_HOWTO[kind].format(name=name, implements=impl_txt), "",
                  "Paste each file into the pane its title names:", ""]
        lines += [f"- [ ] `{f}`: {title}" for f, title in files]
        lines.append("")
    lines += [
        "## 3. Import",
        "",
        "- [ ] *Project → Import PLCopenXML…* → `build/MotionLad_Import.xml`, select all objects.",
        "",
        "## 4. Check after import",
        "",
        "These are kept only in the plain-text declarations (the converter's warnings). Open each "
        "object and make sure the declaration is right:",
        "",
    ]
    lines += [f"- [ ] {w}" for w in warnings] or ["- (no converter warnings)"]
    lines += [
        "",
        "## 5. Project setup",
        "",
        "- [ ] Call `PRG_Main` from the cyclic PLC task.",
        "- [ ] Map `GVL_IO` in the device tree (SoE cyclic data; see `src/README.md`).",
        "- [ ] On the controller: enable the cyclic status data for every axis "
        "(`motion/axs/<name>/cfg/functions/cyclic-status-data/remanent`).",
        "- [ ] Build (F11).",
        "",
    ]
    (man_dir / "README.md").write_text("\n".join(lines), encoding="utf-8")


def tidy_warning(line):
    """'WARNING: /abs/build/st/X.st: attributes ...' -> '`X`: attributes ...'"""
    w = line.removeprefix("WARNING:").strip()
    w = re.sub(r"\S*/build/st/(\w+)\.st", r"`\1`", w)
    w = re.sub(r"^([A-Za-z_]\w*(?:\.\w+)?):", r"`\1`:", w)
    return w


def main():
    st_dir = OUT / "st"
    st_dir.mkdir(parents=True, exist_ok=True)
    for old in st_dir.glob("*.st"):
        old.unlink()

    man_dir = OUT / "manual"
    if man_dir.exists():
        shutil.rmtree(man_dir)
    man_dir.mkdir(parents=True)

    files, manual = [], []
    for path in sorted(SRC.rglob("*.st")):
        text = path.read_text(encoding="utf-8")
        if OOP_RE.search(text):
            manual.append(write_manual(path, man_dir))
            continue
        target = st_dir / path.name
        target.write_text(to_full_st(text), encoding="utf-8")
        files.append(target)

    xml = OUT / "MotionLad_Import.xml"
    result = subprocess.run([sys.executable, str(CONVERTER), *map(str, files), "-o", str(xml),
                             "--name", "MotionLad"], capture_output=True, text=True)
    print(result.stdout, end="")
    print(result.stderr, end="", file=sys.stderr)

    # Warnings can span lines (attribute lists): join continuation lines to their WARNING
    warnings = []
    for line in (result.stdout + result.stderr).splitlines():
        if line.startswith("WARNING:"):
            warnings.append(line)
        elif warnings and line.strip() and not line.startswith(("Wrote", "MANUAL")):
            warnings[-1] += " " + line.strip()
    write_manual_readme(man_dir, sorted(manual, key=lambda o: o[1] != "INTERFACE"),
                        [tidy_warning(w) for w in warnings])

    print(f"{len(files)} objects converted.")
    print(f"Manual steps: {(man_dir / 'README.md').relative_to(ROOT)} "
          f"({len(manual)} objects to create by hand, {len(warnings)} checks)")
    sys.exit(result.returncode)


if __name__ == "__main__":
    main()
